#!/usr/bin/env node
/**
 * Refreshes src/lib/rates.generated.ts from the ECB's published reference
 * rates, via Frankfurter (no key, no account, no rate limit worth worrying
 * about).
 *
 * Runs as `prebuild`, so a deploy bakes current rates into the static export.
 * The site has no server to ask at request time, so build time is the only
 * moment rates can be refreshed at all.
 *
 * It never fails the build. A network error, a blocked host, a malformed
 * payload or a nonsense rate all leave the committed file exactly as it is
 * and exit 0 — stale-but-labelled rates beat a failed deploy, and the figures
 * are marked approximate wherever they are shown. `npm run build` therefore
 * works offline.
 *
 * Rates are stored as RUPEES PER ONE UNIT of the foreign currency, which is
 * the direction the UI divides by. Frankfurter returns the inverse when asked
 * for base=INR, so each one is flipped here rather than in the render path.
 */

import { writeFile, readFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const OUT = join(here, "..", "src", "lib", "rates.generated.ts");

/**
 * What to ask the ECB for. Kept to currencies the ECB actually publishes —
 * anything else would need a second source, and one source with one asof date
 * is easier to reason about than a blend of several.
 */
const SYMBOLS = ["USD", "EUR", "GBP", "AUD", "CAD", "SGD", "JPY"];

/**
 * The dirham is not an ECB reference currency, but it has been hard-pegged at
 * 3.6725 to the dollar since 1997, so it is derived rather than dropped. That
 * is arithmetic on the dollar rate, not an estimate. If the peg ever goes,
 * this constant is the one thing to delete.
 */
const AED_PER_USD = 3.6725;

const ENDPOINT = `https://api.frankfurter.dev/v1/latest?base=INR&symbols=${SYMBOLS.join(",")}`;

/** Four decimals holds the yen (≈0.6 rupees) without implying more. */
const round4 = (n) => Number(n.toFixed(4));

/**
 * A rate is usable only if it is a positive, finite number in a plausible
 * band. The band is deliberately wide — it is here to catch a payload shape
 * change or a zero, not to second-guess the market.
 */
const plausible = (inrPerUnit) =>
  Number.isFinite(inrPerUnit) && inrPerUnit > 0.0001 && inrPerUnit < 100_000;

async function main() {
  const res = await fetch(ENDPOINT, { signal: AbortSignal.timeout(15_000) });
  if (!res.ok) throw new Error(`HTTP ${res.status} ${res.statusText}`);

  const body = await res.json();
  if (!body?.rates || typeof body.rates !== "object") {
    throw new Error("payload has no `rates` object");
  }
  if (typeof body.date !== "string" || !/^\d{4}-\d{2}-\d{2}$/.test(body.date)) {
    throw new Error(`payload has no usable \`date\`: ${JSON.stringify(body.date)}`);
  }

  const inrPerUnit = {};
  for (const code of SYMBOLS) {
    const unitsPerInr = body.rates[code];
    if (typeof unitsPerInr !== "number" || unitsPerInr <= 0) {
      console.warn(`fetch-rates: skipping ${code} — not a positive number`);
      continue;
    }
    const value = round4(1 / unitsPerInr);
    if (!plausible(value)) {
      console.warn(`fetch-rates: skipping ${code} — implausible rate ${value}`);
      continue;
    }
    inrPerUnit[code] = value;
  }

  if (inrPerUnit.USD) {
    inrPerUnit.AED = round4(inrPerUnit.USD / AED_PER_USD);
  }

  // A payload that yields nothing usable is a failure, not an empty table:
  // writing one would silently drop every currency the site offers.
  if (Object.keys(inrPerUnit).length < 2) {
    throw new Error("fewer than two usable rates in the payload");
  }

  const entries = Object.keys(inrPerUnit)
    .sort()
    .map((code) => `  ${code}: ${inrPerUnit[code]},`)
    .join("\n");

  const file = `/**
 * GENERATED by scripts/fetch-rates.mjs — do not edit by hand.
 *
 * Rupees per one unit of each currency, from the ECB's reference rates via
 * Frankfurter. Committed so that \`npm run build\` works offline and so the
 * rates in any given deploy are auditable from the repository.
 *
 * Regenerate with \`npm run rates\`, or just \`npm run build\` (prebuild).
 */

/** The ECB reference date these rates were published for. */
export const RATES_AS_OF = ${JSON.stringify(body.date)};

/** When this file was written, which is when the build last reached the API. */
export const RATES_FETCHED_AT = ${JSON.stringify(new Date().toISOString().slice(0, 10))};

export const INR_PER_UNIT: Record<string, number> = {
${entries}
};
`;

  const previous = await readFile(OUT, "utf8").catch(() => "");
  if (previous === file) {
    console.log(`fetch-rates: unchanged (ECB ${body.date})`);
    return;
  }

  await writeFile(OUT, file, "utf8");
  console.log(
    `fetch-rates: wrote ${Object.keys(inrPerUnit).length} rates (ECB ${body.date})`,
  );
}

main().catch((err) => {
  console.warn(
    `fetch-rates: keeping the committed rates — ${err instanceof Error ? err.message : err}`,
  );
  // Deliberately 0: a rates refresh is an improvement, not a build dependency.
  process.exit(0);
});
